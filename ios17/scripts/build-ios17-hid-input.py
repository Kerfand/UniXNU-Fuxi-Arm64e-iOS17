#!/usr/bin/env python3
"""iOS 17.7 21H16 (arm64e): build the owned NativeHidInput (the fuxi touch digitizer) on the unchanged original IOHIDDevice.

21H16's IOHIDDevice has the 21H461 ABI the iPadOS build qualified: 0xd0 bytes, 207 vtable slots (located without symbols by
scratchpad hidabi.py: the class-name string, the metaclass constructor, getMetaClass, the vtable whose slot 7 it is, the only
function that builds that vptr = C2, and the D2 after it). arm64e adds what build-ios17-legacy-display.py does for the display:
  * the private IOHIDDevice slots 168..206 are declared with names chosen (suffix search) to give each slot's original
    discriminator; the build fails unless all 207 compiled entries match the original's discriminator, key and diversity;
  * calls to original code go through BTI/B adapters (<name> + absolute <name>.original); data stays absolute.
The shared NativeHidInput.cpp refuses arm64e unless it is compiled against a real IOHIDDevice header; this build compiles a copy
without that guard, against the generated original-ABI header, as the arm64 iPadOS build does.
Outputs (build/native-hid-input-ios17): NativeHidInput.late.o, hid-original-bindings.o, hid-original-adapters.o,
hid-ios17-stubs.o, build-report.json; build-ios17-legacy-display.py puts them into libNativeLegacyDisplay.late.a."""
import hashlib, json, os, re, struct, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/native-hid-input-ios17'
OUT.mkdir(parents=True, exist_ok=True)
KC = ROOT.parents[1] / 'ipsw/21H16/kernelcache.decompressed'
sys.path.insert(0, str(ROOT / 'kits/XnuPrelink'))
sys.path.insert(0, str(ROOT / 'scripts'))
from kc_image import Image
from kernel_target import TRIPLE


def require(value, why):
    if not value:
        raise SystemExit('build-ios17-hid-input: ' + why)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(cmd, **kw):
    return subprocess.run([str(c) for c in cmd], check=True, **kw)


SLOTS = 207
HID_VT = 0xfffffff007c2f430
DATA = {'__ZN11IOHIDDevice10gMetaClassE': 0xfffffff00a460100, '__ZTV11IOHIDDevice': HID_VT - 16}
FUNCS = {'__ZN11IOHIDDeviceC2EPK11OSMetaClass': 0xfffffff00991f59c, '__ZN11IOHIDDeviceD2Ev': 0xfffffff00991f5d0}
PURE_TARGET = 0xfffffff008317854   # __cxa_pure_virtual (the Legacy display's abstract slots point here)

raw = KC.read_bytes()
cache = Image(raw)
fx = cache.fixups()
original = [fx.get(HID_VT + 8 * i) for i in range(SLOTS)]
require(all(original) and fx.get(HID_VT + 8 * SLOTS) is None, f'original {SLOTS}-entry IOHIDDevice vtable')
require(all(e[1] for e in original), 'every original vtable entry is authenticated')
PURE = [i for i in range(SLOTS) if original[i][0] == PURE_TARGET]
require(PURE == [180], f'one abstract slot (180, newReportDescriptor) as on 21H461, got {PURE}')
target = [(e[3], e[2], e[4]) for e in original]
# The original constructor: pacibsp; ...; bl IOService C2; adrp/add x16 = this vtable's symbol; add #0x10; ... str [x0].
c2 = struct.unpack('<13I', cache.read(FUNCS['__ZN11IOHIDDeviceC2EPK11OSMetaClass'], 52))
require(c2[0] == 0xd503237f and c2[3] >> 26 == 0x25 and c2[10] == 0xf9000010, 'original constructor shape')
d2 = struct.unpack('<2I', cache.read(FUNCS['__ZN11IOHIDDeviceD2Ev'], 8))
require(d2[0] == 0xd503245f and d2[1] >> 26 == 0x05, 'original destructor: bti c; b IOService D2')
_, fam_at = cache.entries['com.apple.iokit.IOHIDFamily']
fam_img = Image(raw, fam_at)
text = next(s for s in fam_img.segments if s['name'] == '__TEXT_EXEC')
fam_lo, fam_hi = text['va'], text['va'] + text['size']

NAMED = {171: ('OSString *', 'newTransportString', '', ' const', ''),
         173: ('OSString *', 'newProductString', '', ' const', ''),
         180: ('IOReturn', 'newReportDescriptor', 'IOMemoryDescriptor **', ' const', '=0'),
         181: ('IOReturn', 'handleReport', 'IOMemoryDescriptor *,unsigned,IOOptionBits', '', '')}
FIXED = '''// Generated by build-ios17-hid-input.py from the 21H16 original image; opaque private storage only.
#pragma once
#include <IOKit/IOService.h>
#include <IOKit/IOMemoryDescriptor.h>
class IOHIDDevice : public IOService {
 OSDeclareAbstractStructors(IOHIDDevice)
 unsigned char originalPrivate[0xd0-sizeof(IOService)];
public:
 using IOService::setProperty;
 IOReturn Dispatch(IORPC) override;
 void free() override;
 bool init(OSDictionary *properties=nullptr) override;
 bool setProperty(const OSSymbol *,OSObject *) override;
 bool willTerminate(IOService *,IOOptionBits) override;
 IOReturn configureReport(IOReportChannelList *,IOReportConfigureAction,void *,void *) override;
 IOReturn updateReport(IOReportChannelList *,IOReportUpdateAction,void *,void *) override;
 bool start(IOService *) override;
 void stop(IOService *) override;
 bool handleOpen(IOService *,IOOptionBits,void *) override;
 void handleClose(IOService *,IOOptionBits) override;
 bool handleIsOpen(const IOService *) const override;
 bool matchPropertyTable(OSDictionary *,SInt32 *) override;
 IOReturn message(UInt32,IOService *,void *) override;
 IOReturn newUserClient(task_t,void *,UInt32,OSDictionary *,IOUserClient **) override;
'''


def header(suffix):
    text = FIXED
    defines = []
    for i in range(168, SLOTS):
        s = suffix.get(i, '')
        if i in NAMED:
            ret, name, params, const, pure = NAMED[i]
            text += f' virtual {ret} {name}{s}({params}){const}{pure};\n'
            if s:
                defines.append(f'#define {name} {name}{s}\n')
        else:
            text += f' virtual __attribute__((deprecated("Unqualified prototype: never call from source"))) void opaque{i}{s}();\n'
    text += '};\nstatic_assert(sizeof(IOHIDDevice)==0xd0,"Original device instance size");\n'
    pre = '// Generated by build-ios17-hid-input.py (21H16 arm64e).\n' + ''.join(defines)
    return text.replace('#pragma once\n', '#pragma once\n' + pre, 1)


def macho(path):
    d = Path(path).read_bytes()
    require(struct.unpack_from('<I', d)[0] == 0xfeedfacf, f'{path} is a 64-bit Mach-O object')
    ncmds = struct.unpack_from('<I', d, 16)[0]
    off, sections, symtab = 32, [], None
    for _ in range(ncmds):
        cmd, size = struct.unpack_from('<II', d, off)
        if cmd == 0x19:
            nsects = struct.unpack_from('<I', d, off + 64)[0]
            for s in range(nsects):
                so = off + 72 + 80 * s
                sect, seg = d[so:so + 16].rstrip(b'\0').decode(), d[so + 16:so + 32].rstrip(b'\0').decode()
                addr, sz, fo, _, reloff, nreloc = struct.unpack_from('<QQIIII', d, so + 32)
                sections.append(dict(seg=seg, sect=sect, addr=addr, size=sz, off=fo, reloff=reloff, nreloc=nreloc))
        elif cmd == 2:
            symtab = struct.unpack_from('<4I', d, off + 8)
        off += size
    symoff, nsyms, stroff, _ = symtab
    syms = []
    for i in range(nsyms):
        strx, ntype, nsect, ndesc, value = struct.unpack_from('<IBBHQ', d, symoff + 16 * i)
        name = d[stroff + strx:d.index(b'\0', stroff + strx)].decode()
        syms.append(dict(name=name, type=ntype, sect=nsect, value=value))
    return d, sections, syms


def vtable_entries(path):
    d, sections, syms = macho(path)
    vt = next((s for s in syms if s['name'] == '__ZTV14NativeHidInput' and s['type'] & 0x0e == 0x0e), None)
    require(vt, 'compiled vtable __ZTV14NativeHidInput')
    sec = next(s for s in sections if s['addr'] <= vt['value'] < s['addr'] + s['size'])
    relocs = {}
    for k in range(sec['nreloc']):
        address, info = struct.unpack_from('<iI', d, sec['reloff'] + 8 * k)
        symnum, extern, rtype = info & 0xffffff, (info >> 27) & 1, info >> 28
        relocs[sec['addr'] + address] = (syms[symnum]['name'] if extern else None, rtype)
    entries = []
    for i in range(SLOTS):
        at = vt['value'] + 16 + 8 * i
        name, rtype = relocs.get(at, (None, None))
        require(name and rtype == 11, f'slot {i}: authenticated pointer relocation to a symbol ({name}, type {rtype})')
        word = struct.unpack_from('<Q', d, sec['off'] + at - sec['addr'])[0]
        entries.append(dict(name=name, div=(word >> 32) & 0xffff, addr=(word >> 48) & 1, key=(word >> 49) & 3,
                            auth=word >> 63))
    require((vt['value'] + 16 + 8 * SLOTS) not in relocs, f'exactly {SLOTS} compiled vtable entries')
    return entries, syms


# The discriminator search tool and model are build-ios17-legacy-display.py's.
legacy = (ROOT / 'scripts/build-ios17-legacy-display.py').read_text()
SEARCH_C = re.search(r"SEARCH_C = r'''(.*?)'''\n", legacy, re.S).group(1)
exec(re.search(r'(def disc\(text\):.*?)\n\n\n', legacy, re.S).group(1))
MANGLED = re.compile(r'^_ZN(K?)(14NativeHidInput|11IOHIDDevice)(\d+)(.*)$')


def introducing(symbol):
    m = MANGLED.match(symbol[1:])
    require(m, 'unexpected HID vtable symbol ' + symbol)
    const, _, length, tail = m.groups()
    return f'_ZN{const}11IOHIDDevice', tail[:int(length)], tail[int(length):]


# ---- compile (the probe's record: iokit IOPlatformExpert.cpp) ----
record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json')
                    .read_text().strip().rstrip(','))
shared = (ROOT / 'drivers/NativeHidInput/NativeHidInput.cpp').read_text()
guard = ('#if defined(__arm64e__) && !(defined(NATIVE_HID_SOURCE_API) && NATIVE_HID_SOURCE_API)\n'
         '#error "The original HID ABI path is arm64 iOS 17 only; use the source API build for arm64e."\n#endif\n')
require(shared.count(guard) == 1, 'NativeHidInput.cpp arm64e guard anchor')
# The shared hook carries a 24A446 IOHIDEventDriver ABI, which is not qualified for 21H16.
edge_call='if(driver && (touchEnabled || touchOnly))edge::install(driver);'
require(shared.count(edge_call)==1,'one optional edge-hook installation')
shared=shared.replace(edge_call,'if(false && driver && (touchEnabled || touchOnly))edge::install(driver); // 21H16: edge hook unqualified')
SRC = OUT / 'NativeHidInput.cpp'
# Optional iOS digitizer-only diagnostic, preserving the shared iPadOS source.
start_marker = 'bool start(IOService *provider) override {'
require(shared.count(start_marker) == 1, 'one HID start override')
shared = shared.replace(start_marker, start_marker +
    ' unsigned digitizerOnly=0; '
    'if(PE_parse_boot_argn("fuxi-touch-digitizer-only",&digitizerOnly,sizeof(digitizerOnly)) && digitizerOnly==1)touchOnly=true; ')
# fuxi buttons (docs/zh/porting/input.md section 4): with fuxi-buttons=1 the digitizer-only device also carries a Consumer
# Control collection (report 2: bit0 Menu, bit1 Power, bit2 Volume Increment, bit3 Volume Decrement, as the shared descriptor)
# after the digitizer, so the digitizer stays the primary usage, and registers the button sink (FuxiButtons.cpp).
shared = shared.replace(start_marker + ' unsigned digitizerOnly=0; ', start_marker + ' unsigned digitizerOnly=0; '
    '{unsigned b=0; ios17TouchButtons=PE_parse_boot_argn("fuxi-buttons",&b,sizeof(b)) && b==1;} ')
desc_old = 'if(touchOnly){size=sizeof(touchDescriptor);memcpy(combined,touchDescriptor,size);}'
require(shared.count(desc_old) == 1, 'touch-only descriptor anchor')
shared = shared.replace(desc_old, 'if(touchOnly){size=sizeof(touchDescriptor);memcpy(combined,touchDescriptor,size);'
    'if(ios17TouchButtons){memcpy(combined+size,ios17ConsumerDescriptor,sizeof(ios17ConsumerDescriptor));size+=sizeof(ios17ConsumerDescriptor);}}')
for sink_old in ('if(!touchOnly && &native_buttons_set_sink)native_buttons_set_sink(&NativeHidInput::buttonsNotify,this);',
                 'if(!touchOnly && &native_buttons_set_sink)native_buttons_set_sink(nullptr,nullptr);'):
    require(shared.count(sink_old) == 1, 'button sink anchor')
    shared = shared.replace(sink_old, sink_old.replace('!touchOnly', '(!touchOnly || ios17TouchButtons)'))
desc_anchor = '#define TOUCH_FINGERS 10\n'
require(shared.count(desc_anchor) == 1, 'TOUCH_FINGERS anchor')
shared = shared.replace(desc_anchor, desc_anchor + 'static bool ios17TouchButtons;\n'
    'static_assert(sizeof(descriptor) >= 33, "consumer collection fits the combined buffer");\n'
    'static const unsigned char ios17ConsumerDescriptor[]={0x05,0x0c,0x09,0x01,0xa1,0x01,0x85,0x02,'
    '0x09,0x40,0x09,0x30,0x09,0xe9,0x09,0xea,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x04,0x81,0x02,'
    '0x75,0x04,0x95,0x01,0x81,0x03,0xc0};\n')
SRC.write_text('// ios17 copy (build-ios17-hid-input.py): the original-ABI header is generated for 21H16 arm64e.\n'
               + shared.replace(guard, ''))
OBJ = OUT / 'NativeHidInput.o'


def compile_cmd(source, obj, extra):
    args, cmd, k = record['arguments'], [], 0
    while k < len(args):
        a = args[k]
        if a == record['file']:
            cmd.append(str(source))
        elif a == '-o':
            cmd += ['-o', str(obj)]; k += 1
        elif a in ('-MF', '-MT', '-MJ'):
            k += 1
        elif a == '-Xclang' and args[k + 1].startswith('-W'):
            k += 1
        elif not a.startswith('-W'):
            cmd.append(a)
        k += 1
    return cmd + ['-Wall', '-Wextra', '-Werror', '-Wno-unknown-warning-option', '-Wno-unused-parameter',
                  '-Wno-unnecessary-virtual-specifier', '-Wno-c99-designator', '-Wno-reorder-init-list',
                  '-Wno-deprecated-enum-enum-conversion', '-Wno-deprecated-declarations',
                  '-Wno-missing-designated-field-initializers',
                  '-I', str(ROOT / '.cache/xnu-work/osfmk')] + [str(x) for x in extra]


def compile_hid(suffix):
    (OUT / 'OriginalHidDeviceABI.h').write_text(header(suffix))
    subprocess.run(compile_cmd(SRC, OBJ, ['-I', OUT]), cwd=record['directory'], check=True)
    return vtable_entries(OBJ)


entries, _ = compile_hid({})
bad_low = [i for i in range(168) if (entries[i]['div'], entries[i]['key'], entries[i]['addr']) != target[i]]
require(not bad_low, f'IOService-ancestry vtable discriminators differ from the original at slots {bad_low}')
# The IOService slots the original IOHIDDevice overrides (its own code) are exactly those this declaration overrides.
for i in range(168):
    e = entries[i]
    if e['name'].startswith(('__ZN14NativeHidInput', '__ZNK14NativeHidInput')):
        continue
    in_hid = fam_lo <= original[i][0] < fam_hi
    require(in_hid == ('11IOHIDDevice' in e['name']), f'slot {i}: original override set differs ({e["name"]}, original in IOHIDFamily {in_hid})')
jobs = []
for i in range(168, SLOTS):
    e = entries[i]
    pre, name, rest = introducing(e['name'])
    require(disc(pre + str(len(name)) + name + rest) == e['div'], f'slot {i}: discriminator model disagrees with clang')
    if e['div'] != target[i][0]:
        jobs.append((i, pre, name, rest or '-', target[i][0]))
print(f'build-ios17-hid-input: {len(jobs)} IOHIDDevice slots need discriminator-matching names')
suffix = {}
if jobs:
    with tempfile.TemporaryDirectory() as t:
        src, exe = Path(t, 's.c'), Path(t, 's')
        src.write_text(SEARCH_C)
        host_cc = next((c for c in ('/usr/bin/gcc', '/usr/bin/cc') if os.path.exists(c)), 'cc')
        host_env = {k: v for k, v in os.environ.items() if k not in ('CPATH', 'C_INCLUDE_PATH', 'SDKROOT', 'CFLAGS',
                                                                       'CC', 'LIBRARY_PATH', 'COMPILER_PATH')}
        host_env['PATH'] = '/usr/bin:/bin'
        subprocess.run([host_cc, '-O2', '-o', str(exe), str(src)], check=True, env=host_env)
        res = subprocess.run([str(exe)], input=''.join(f'{p} {n} {r} {w:x}\n' for _, p, n, r, w in jobs),
                             capture_output=True, text=True, check=True).stdout.split()
    for (i, *_), s in zip(jobs, res):
        require(s != '-', f'no discriminator-matching name found for slot {i}')
        suffix[i] = s
entries, syms = compile_hid(suffix)
for i in range(SLOTS):
    e, o = entries[i], target[i]
    require(e['auth'] and (e['div'], e['key'], e['addr']) == o,
            f'slot {i} ({e["name"]}): div/key/addr {e["div"]:#x}/{e["key"]}/{e["addr"]} vs original {o[0]:#x}/{o[1]}/{o[2]}')
owned = [i for i, e in enumerate(entries) if e['name'].startswith(('__ZN14NativeHidInput', '__ZNK14NativeHidInput'))]
require(180 in owned, 'the abstract report-descriptor slot is implemented')

# ---- bindings ----
undefined = {s['name'] for s in syms if s['type'] & 0x0e == 0 and s['type'] & 1}
functions = dict(FUNCS)
for i, e in enumerate(entries):
    if '11IOHIDDevice' in e['name']:
        require(i not in PURE, f'abstract slot {i} bound to the original')
        functions[e['name']] = original[i][0]
hid_imports = {n for n in undefined if '11IOHIDDevice' in n}
require(hid_imports <= set(functions) | set(DATA), f'unbound original imports {sorted(hid_imports - set(functions) - set(DATA))}')
bound = {n: functions[n] for n in sorted(hid_imports) if n in functions}
absolute = ['// Generated by build-ios17-hid-input.py: original 21H16 addresses.']
for name, value in sorted(DATA.items()):
    if name in undefined:
        absolute += [f'.globl "{name}"', f'.set "{name}", {value:#x}']
for name, value in bound.items():
    absolute += [f'.globl "{name}.original"', f'.set "{name}.original", {value:#x}']
adapters = ['// Generated by build-ios17-hid-input.py: BTI/B adapters to original 21H16 code.', '.text']
for name in bound:
    adapters += [f'.globl "{name}"', '.p2align 2', f'"{name}":', '  bti c', f'  b "{name}.original"']
(OUT / 'hid-original-bindings.S').write_text('\n'.join(absolute) + '\n')
(OUT / 'hid-original-adapters.S').write_text('\n'.join(adapters) + '\n')
clang = record['arguments'][0]
for stem in ('hid-original-bindings', 'hid-original-adapters'):
    run([clang, '-target', TRIPLE, '-c', OUT / f'{stem}.S', '-o', OUT / f'{stem}.o'])
# The button driver is not part of this port: its sink stays empty (arm64e links no undefined weak import).
stub = OUT / 'hid-ios17-stubs.c'
stub.write_text('// build-ios17-hid-input.py: weak fallback; FuxiButtons.cpp (display archive) defines the real sink.\n#include <stdint.h>\n'
                'void native_buttons_set_sink(void (*sink)(void *, uint32_t), void *context);\n'
                '__attribute__((weak)) void native_buttons_set_sink(void (*sink)(void *, uint32_t), void *context) {(void)sink; (void)context;}\n')
startup = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/osfmk/DEVELOPMENT/startup.o.json')
                     .read_text().strip().rstrip(','))
sargs, scmd, k = startup['arguments'], [], 0
while k < len(sargs):
    a = sargs[k]
    if a == startup['file']:
        scmd.append(str(stub))
    elif a == '-o':
        scmd += ['-o', str(OUT / 'hid-ios17-stubs.o')]; k += 1
    elif a in ('-MF', '-MT', '-MJ'):
        k += 1
    elif a == '-Xclang' and sargs[k + 1].startswith('-W'):
        k += 1
    elif not a.startswith('-W'):
        scmd.append(a)
    k += 1
subprocess.run(scmd + ['-mgeneral-regs-only'], cwd=startup['directory'], check=True)
late = OUT / 'NativeHidInput.late.o'
run(['llvm-objcopy', '--remove-section=__DATA,__mod_init_func', '--globalize-symbol=__GLOBAL__sub_I_NativeHidInput.cpp', OBJ, late])
(OUT / 'build-report.json').write_text(json.dumps(dict(
    kernelcache_sha256=sha(KC), hid_vtable=hex(HID_VT), renamed_slots={str(i): s for i, s in sorted(suffix.items())},
    owned_slots=owned, bound=len(bound), source_sha256=sha(ROOT / 'drivers/NativeHidInput/NativeHidInput.cpp')), indent=2) + '\n')
print(f'build-ios17-hid-input: {len(suffix)} renamed slots, owned {owned}, {len(bound)} adapters')

