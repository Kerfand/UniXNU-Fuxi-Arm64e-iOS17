"""mkskel.py: device/package/DataSkel21H16.h - the 21H16 OS volume's /private/var template (what scripts/make-data-seed.py copies into
a first-install Data seed), as a table the kernel applies after the scratch Data mount (BootWatchdogPolicy.c, sheng-data-skel=1):
directories with their template owner and mode, the timezone symlink and the small template files (created only when absent).
staged_system_apps and MobileAsset/PreinstalledAssetsV2 are left out (sheng-staged-apps copies the former; the latter is asset payload).
Source: 7z -slt listing of 044-18520-018.dmg private/var (owner, group, mode) and the files' bytes, read-only."""
import re, subprocess, tempfile
from pathlib import Path
R = Path('/home/xiaomi/sadnut-fuxi-local-20261103')
DMG = '/mnt/f/UniXNU-FUXI-work/ios17-cache/ipsw-21H16/044-18520-018.dmg'
t = open('/home/xiaomi/ios17-bins-21H16/varls.txt', errors='replace').read()
EXCL = ('staged_system_apps', 'MobileAsset/PreinstalledAssetsV2')
items = []
for block in t.split('\n\n'):
    g = lambda k: (re.search(r'^' + re.escape(k) + r' = (.*)$', block, re.M) or [None, None])[1]
    p = g('Path')
    if not p or not p.startswith('private/var/'):
        continue
    rel = p[len('private/var/'):]
    if rel.startswith(EXCL):
        continue
    items.append(dict(rel=rel, mode=g('Mode') or '', uid=int(g('User ID') or 0), gid=int(g('Group ID') or 0),
                      link=g('Symbolic Link') or '', size=int(g('Size') or 0)))


def perm(s):
    bits = 0
    for i, (ch, bit) in enumerate(zip(s[1:10], (0o400, 0o200, 0o100, 0o40, 0o20, 0o10, 0o4, 0o2, 0o1))):
        if ch in 'rwx': bits |= bit
        if i == 2 and ch in 'sS': bits |= 0o4000 | (bit if ch == 's' else 0)
        if i == 5 and ch in 'sS': bits |= 0o2000 | (bit if ch == 's' else 0)
        if i == 8 and ch in 'tT': bits |= 0o1000 | (bit if ch == 't' else 0)
    return bits


dirs = sorted((i for i in items if i['mode'].startswith('d')), key=lambda i: (i['rel'].count('/'), i['rel']))
links = [i for i in items if i['mode'].startswith('l')]
files = [i for i in items if i['mode'].startswith('-') and i['size'] <= 2048]
with tempfile.TemporaryDirectory() as d:
    subprocess.run(['7z', 'x', '-y', '-bso0', '-bsp0', f'-o{d}', DMG] + ['private/var/' + f['rel'] for f in files], check=True)
    for f in files:
        f['data'] = (Path(d) / 'private/var' / f['rel']).read_bytes()
        assert len(f['data']) == f['size'], f['rel']


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


out = ['// Generated by mkskel.py from the iOS 17.7 21H16 OS volume (044-18520-018.dmg) /private/var template. Do not edit.',
       '// kind: 0 directory, 1 symlink (data = target), 2 file created only when absent (data = contents).',
       'struct sheng_skel_entry { const char *path; unsigned short mode; unsigned short uid, gid; unsigned char kind; unsigned short size; const char *data; };',
       'static const struct sheng_skel_entry sheng_skel_21h16[] = {']
for i in dirs:
    out.append(f' {{{cstr("/private/var/" + i["rel"])}, 0{perm(i["mode"]):o}, {i["uid"]}, {i["gid"]}, 0, 0, 0}},')
for i in links:
    out.append(f' {{{cstr("/private/var/" + i["rel"])}, 0755, {i["uid"]}, {i["gid"]}, 1, {len(i["link"])}, {cstr(i["link"])}}},')
for i in files:
    data = ''.join(f'\\x{b:02x}' for b in i['data'])
    out.append(f' {{{cstr("/private/var/" + i["rel"])}, 0{perm(i["mode"]):o}, {i["uid"]}, {i["gid"]}, 2, {len(i["data"])}, "{data}"}},')
out.append('};')
(R / 'device/package/DataSkel21H16.h').write_text('\n'.join(out) + '\n')
print('dirs', len(dirs), 'links', len(links), 'files', len(files), [f['rel'] for f in files])
for i in dirs[:6] + [x for x in dirs if x['rel'] in ('Keychains', 'mobile/Library/Application Support', 'tmp', 'mobile')]:
    print(f"  {perm(i['mode']):o} {i['uid']}:{i['gid']} {i['rel']}")
